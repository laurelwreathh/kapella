// Run with node scripts/test-state.cjs. No test framework dependency is needed.
/* eslint-disable @typescript-eslint/no-require-imports -- Standalone CommonJS test runner. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
require.extensions['.ts'] = (module, filename) => {
  const source = fs.readFileSync(filename, 'utf8');
  const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  module._compile(output.replace(/require\("@\/(.*?)"\)/g, (_, relative) => `require(${JSON.stringify(path.join(root, relative))})`), filename);
};
const { tracks } = require('../lib/demo-music.ts');
const { listeningReducer, initialListeningState } = require('../lib/listening-state.ts');
const { emptyLibraryData, parseLibraryStorage, saveLibraryStorage, loadLibraryStorage } = require('../lib/library-storage.ts');
const { initialPlayerState, playerReducer, shuffledQueue } = require('../lib/player-state.ts');
const { buildTasteProfile } = require('../lib/taste-profile.ts');
const { recommendTracks } = require('../lib/recommendations.ts');
const { tasteProfileKey } = require('../lib/taste-profile.ts');

let data = emptyLibraryData();
data = { ...data, ...listeningReducer(data, { type: 'recordPlayback', trackId: 13, playedAt: 1000 }) };
const profile = buildTasteProfile(data, tracks, 2000);
const mix = recommendTracks(profile);
data = { ...data, ...listeningReducer(data, { type: 'setGuestMode', enabled: true }) };
for (let i = 0; i < 1200; i++) data = { ...data, ...listeningReducer(data, { type: 'recordPlayback', trackId: 19, playedAt: 2000 + i }) };
assert.equal(data.history.length, 1);
assert.equal(data.guestHistory.length, 500);
assert.deepEqual(buildTasteProfile(data, tracks, 2000), profile);
assert.deepEqual(recommendTracks(buildTasteProfile(data, tracks, 2000)), mix);
assert.equal(new Set([...data.history, ...data.guestHistory].map(entry => entry.id)).size, 501);
data.favoriteIds = [13];
data.playlists = [{ id: 'demo', name: 'Мой микс', description: '', trackIds: [13, 14] }];
data.followedArtistIds = ['pulse-city'];
const restored = parseLibraryStorage(JSON.stringify({ version: 1, ...data }));
assert.equal(restored.guestMode, true);
assert.deepEqual(restored.favoriteIds, [13]);
assert.deepEqual(restored.playlists, data.playlists);
assert.deepEqual(restored.followedArtistIds, ['pulse-city']);
assert.equal(restored.guestHistory.length, 500);
assert.deepEqual(recommendTracks(buildTasteProfile(restored, tracks, 2000)), recommendTracks(buildTasteProfile(data, tracks, 2000)));
const contaminated = parseLibraryStorage(JSON.stringify({ version: 1, ...data, history: [data.guestHistory[0], ...data.history], favoriteIds: [999, 13, 13], playlists: [...data.playlists, { id: '../bad', name: 'bad', description: '', trackIds: [999] }] }));
assert.equal(contaminated.history.length, 1);
assert.deepEqual(contaminated.favoriteIds, [13]);
assert.equal(contaminated.playlists.length, 1);
const tasteKey = tasteProfileKey(data);
const shown = { tasteKey, trackIds: [13, 14], shownAt: 3000 };
const exposures = parseLibraryStorage(JSON.stringify({ version: 1, ...data, recommendationHistory: [shown, shown, { ...shown, tasteKey: 'invalid' }, { ...shown, shownAt: 'bad' }] }));
assert.equal(exposures.recommendationHistory.length, 1, 'Recommendation metadata must be validated and deduplicated');
assert.equal(tasteProfileKey(exposures), tasteKey, 'Library hydration must preserve taste keys despite event ID normalization');
assert.deepEqual(parseLibraryStorage(JSON.stringify({ version: 1, ...data, recommendationHistory: undefined })).recommendationHistory, [], 'Old libraries must load without exposure metadata');
assert.deepEqual(parseLibraryStorage('{broken'), emptyLibraryData());
assert.deepEqual(parseLibraryStorage('{"version":99}'), emptyLibraryData());
global.window = { get localStorage() { throw new Error('Storage denied'); } };
assert.doesNotThrow(() => saveLibraryStorage('test-user', data));
assert.deepEqual(loadLibraryStorage('test-user'), emptyLibraryData());
data = listeningReducer(restored, { type: 'setGuestMode', enabled: false });
data = listeningReducer(data, { type: 'recordPlayback', trackId: 14, playedAt: 4000 });
assert.equal(data.history.length, 2);
assert.equal(data.history[0].mode, 'normal');
assert.equal(initialListeningState.history.length, 0);

const queue = tracks.slice(0, 3);
let state = initialPlayerState(queue);
state = playerReducer(state, { type: 'select', queue, index: 0 });
state = playerReducer(state, { type: 'tick', elapsed: 12 });
state = playerReducer(state, { type: 'toggle' });
assert.equal(state.playing, false);
assert.equal(playerReducer(state, { type: 'tick', elapsed: 5 }).time, 12);
state = playerReducer(state, { type: 'toggle' });
state = playerReducer(state, { type: 'seek', time: 999 });
assert.equal(state.time, state.duration);
state = playerReducer(state, { type: 'next' });
assert.equal(state.index, 1);
state = playerReducer(state, { type: 'previous' });
assert.equal(state.index, 0);
state = playerReducer(state, { type: 'enqueue', track: tracks[12] });
assert.equal(state.queue[1].id, 13);
assert.equal(state.queue[0].id, 1);
assert.equal(new Set(state.queue.map(track => track.id)).size, state.queue.length);
const randomQueue = shuffledQueue(state.queue, state.queue[state.index].id);
assert.equal(randomQueue[0].id, state.queue[state.index].id);
assert.deepEqual([...randomQueue.map(track => track.id)].sort(), [...state.queue.map(track => track.id)].sort());
state = playerReducer(state, { type: 'select', queue, index: queue.length - 1 });
const ended = playerReducer(state, { type: 'ended' });
assert.equal(ended.playing, false);
assert.equal(ended.time, ended.duration);
assert.equal(playerReducer(state, { type: 'next' }).index, 0);
state = playerReducer(state, { type: 'repeat' });
assert.equal(playerReducer(state, { type: 'ended' }).index, 0);
state = playerReducer(state, { type: 'repeat' });
const repeated = playerReducer(state, { type: 'ended' });
assert.equal(repeated.index, state.index);
assert.equal(repeated.time, 0);
assert(repeated.revision > state.revision);
assert.equal(playerReducer(state, { type: 'volume', volume: 2 }).volume, 1);
console.log('PASS: guest isolation end-to-end, storage recovery/validation/caps, restored personalization, denied storage, Player controls/queue/repeat');
